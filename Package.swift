// swift-tools-version:5.9
import PackageDescription

// The analyzer and renderer libraries build on macOS and Windows. Quick Look,
// the project-access service and its XPC/bookmark plumbing are macOS-only.
var products: [Product] = [
    .library(name: "FourDFileKit", targets: ["FourDFileKit"]),
    .library(name: "FourDRender", targets: ["FourDRender"]),
    .executable(name: "fourdql", targets: ["fourdql"]),
]

let windowsServices = Target.Dependency.target(name: "CFourDWindows", condition: .when(platforms: [.windows]))

var targets: [Target] = [
    // Windows Imaging Component and DirectWrite adapters (empty on other platforms).
    .target(name: "CFourDWindows",
            linkerSettings: [
                .linkedLibrary("windowscodecs", .when(platforms: [.windows])),
                .linkedLibrary("dwrite", .when(platforms: [.windows])),
                .linkedLibrary("ole32", .when(platforms: [.windows])),
            ]),

    // Analyzer layer: bytes -> typed, Codable models. No UI, no HTML.
    .target(name: "FourDFileKit", dependencies: [windowsServices]),

    // Rendering layer: typed models -> generic Report -> HTML.
    .target(name: "FourDRender", dependencies: ["FourDFileKit", windowsServices]),

    // Command line tool for development: inspect a file as text, JSON or HTML.
    .executableTarget(name: "fourdql", dependencies: ["FourDFileKit", "FourDRender"]),
]

#if os(macOS)
targets += [
    .target(name: "FourDProjectAccess"),
    .target(name: "FourDQuickLookUI", linkerSettings: [.linkedFramework("WebKit")]),

    .executableTarget(name: "FourDProjectPreviewService",
                      dependencies: ["FourDProjectAccess", "FourDFileKit", "FourDRender"]),

    // Quick Look preview extension binary (bundled into an .appex by scripts/build.sh).
    .executableTarget(
        name: "FourDQuickLookExtension",
        dependencies: ["FourDFileKit", "FourDRender", "FourDProjectAccess", "FourDQuickLookUI"],
        linkerSettings: [
            .unsafeFlags(["-Xlinker", "-e", "-Xlinker", "_NSExtensionMain"]),
            .linkedFramework("QuickLookUI"),
        ]
    ),

    // Hosting app forwards explicit folder grants to the sandboxed service.
    .executableTarget(name: "FourDQuickLookHost", dependencies: ["FourDProjectAccess"],
                      linkerSettings: [.linkedFramework("QuickLookUI")]),
]
let testDependencies: [Target.Dependency] = ["FourDFileKit", "FourDRender", "FourDProjectAccess", "FourDQuickLookUI"]
#else
let testDependencies: [Target.Dependency] = ["FourDFileKit", "FourDRender"]
#endif

// Fixtures are generated by scripts/make-fixtures.sh (needs tool4d).
targets.append(.testTarget(name: "FourDFileKitTests", dependencies: testDependencies,
                           resources: [.copy("Fixtures")]))

let package = Package(
    name: "FourDQuickLook",
    platforms: [.macOS(.v12)],
    products: products,
    targets: targets,
    cxxLanguageStandard: .cxx17
)
