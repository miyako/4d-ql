#!/usr/bin/env python3
"""Regenerates Sources/FourDRender/FormSubstituteFontData.swift.

Selawik (Microsoft, SIL OFL 1.1, Reserved Font Name "Selawik") is the
open-source metric-compatible fallback for Segoe UI. The release files are
embedded byte-for-byte; the OFL forbids distributing modified versions under the
reserved name, so do not subset or rename them. The license is ThirdParty/Selawik/OFL.txt.

Usage: scripts/embed-selawik.py [Selawik_Release.zip]
"""
import base64
import hashlib
import io
import sys
import urllib.request
import zipfile
from pathlib import Path

RELEASE = "https://github.com/microsoft/Selawik/releases/download/1.01/Selawik_Release.zip"
SHA256 = "3f62c51e05e3b5a1e6241cf92a371f0be2ea1183aa87b30718bbd40832a8d423"
FILES = {
    "regularTrueType": "selawk.ttf",
    "boldTrueType": "selawkb.ttf",
    "regularWOFF2": "selawk.woff2",
    "boldWOFF2": "selawkb.woff2",
}
OUTPUT = Path(__file__).resolve().parent.parent / "Sources/FourDRender/FormSubstituteFontData.swift"


def main() -> None:
    data = Path(sys.argv[1]).read_bytes() if len(sys.argv) > 1 else urllib.request.urlopen(RELEASE).read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        sys.exit(f"unexpected Selawik release checksum {digest}")
    archive = zipfile.ZipFile(io.BytesIO(data))
    lines = [
        "// Generated by scripts/embed-selawik.py from Selawik 1.01. Do not edit.",
        "// Copyright 2015, Microsoft Corporation, with Reserved Font Name Selawik.",
        "// Licensed under the SIL Open Font License 1.1; see ThirdParty/Selawik/OFL.txt.",
        "",
        "extension FormSubstituteFont {",
    ]
    for name, member in FILES.items():
        encoded = base64.b64encode(archive.read(member)).decode("ascii")
        lines.append(f"    /// Unmodified `{member}`, base64-encoded.")
        lines.append(f'    static let {name} = "{encoded}"')
    lines.append("}")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
